/** EN/UA field and section labels for expat builder forms (sublease, POA, car). */

export type ExpatSectionDef = { title: string; subtitle?: string };
export type ExpatLabelPack = {
  sections: Record<string, ExpatSectionDef>;
  fields: Record<string, string>;
  options?: Record<string, string>;
};

export function expatFieldLabel(
  fields: Record<string, string>,
  key: string,
  fallback: string,
): string {
  return fields[key] ?? fallback;
}

export function expatSection(
  sections: Record<string, ExpatSectionDef>,
  key: string,
  title: string,
  subtitle?: string,
): ExpatSectionDef {
  const s = sections[key];
  if (s) return s;
  return { title, subtitle };
}

